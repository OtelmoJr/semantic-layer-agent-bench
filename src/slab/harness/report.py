"""Generate report.md and a chart from the results table only. No number in the report
is typed by hand."""

from __future__ import annotations

from pathlib import Path

from slab import config
from slab.harness import stats
from slab.harness.store import ResultStore

ARM_NAMES = {"A": "A raw schema", "B": "B raw + glossary", "C": "C semantic layer"}
CATS = ["simple", "multi_join", "time", "business_definition", "out_of_coverage"]


def _pct(x: float) -> str:
    return "n/a" if x != x else f"{100 * x:.1f}%"


def _chart(scores: list[stats.ArmScore], path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    models = sorted({s.model for s in scores})
    arms = ["A", "B", "C"]
    colors = {"A": "#8b949e", "B": "#e3b341", "C": "#3fb6a8"}
    fig, ax = plt.subplots(figsize=(8, 4.5), dpi=150)
    width = 0.8 / len(arms)
    for j, arm in enumerate(arms):
        xs, ys, err = [], [], [[], []]
        for i, m in enumerate(models):
            s = next((s for s in scores if s.model == m and s.arm == arm), None)
            if s is None:
                continue
            xs.append(i + (j - 1) * width)
            ys.append(100 * s.ex)
            err[0].append(100 * (s.ex - s.ci_low))
            err[1].append(100 * (s.ci_high - s.ex))
        ax.bar(xs, ys, width, yerr=err, capsize=3, label=ARM_NAMES[arm], color=colors[arm])
    ax.set_xticks(range(len(models)), models)
    ax.set_ylabel("Execution accuracy (%)")
    ax.set_ylim(0, 100)
    ax.legend(frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    ax.set_title("Execution accuracy by arm (95% bootstrap CI over questions)")
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def build(run_ids: list[str], out_dir: Path, split: str | None = "holdout") -> Path:
    table = ResultStore().read(run_ids)
    rows = table.to_pylist()
    if split:
        rows = [r for r in rows if r["split"] == split]
    if not rows:
        raise SystemExit("no results for the given runs/split")
    out_dir.mkdir(parents=True, exist_ok=True)
    scores = stats.arm_scores(rows)
    models = sorted({r["model_id"] for r in rows})
    lines = [
        "# Results",
        "",
        f"Runs: {', '.join(run_ids)} · split: {split or 'all'} · gold hash: `{rows[0]['gold_hash'][:12]}`",
        "",
        "Generated by `slab report` from the results table. Unit of analysis is the question;",
        "attempts are averaged per question and the bootstrap resamples questions.",
        "",
        "## Execution accuracy",
        "",
        "| model | arm | questions | EX | 95% CI | pass^k |",
        "|---|---|---|---|---|---|",
    ]
    for s in scores:
        lines.append(f"| {s.model} | {ARM_NAMES.get(s.arm, s.arm)} | {s.n_questions} | {_pct(s.ex)} | "
                     f"{_pct(s.ci_low)} – {_pct(s.ci_high)} | {_pct(s.pass_all)} |")

    lines += ["", "## Paired comparisons (McNemar, majority vote per question)", "",
              "| model | comparison | Δ EX | 95% CI | only left right | only right right | p |",
              "|---|---|---|---|---|---|---|"]
    for m in models:
        for x, y in (("A", "B"), ("A", "C"), ("B", "C")):
            t = stats.paired_test(rows, m, x, y)
            if t:
                lines.append(f"| {m} | {x} → {y} | {100 * t.diff:+.1f} pp | {100 * t.ci_low:+.1f} – "
                             f"{100 * t.ci_high:+.1f} pp | {t.x_only} | {t.y_only} | {t.p_value:.3f} |")

    lines += ["", "## H2: how much of the semantic layer's gain is documentation?", "",
              "Share = (EX_B − EX_A) / (EX_C − EX_A). Near 1: the glossary alone explains the gain.", ""]
    for m in models:
        d = stats.documentation_share(rows, m)
        lines.append(f"- {m}: " + ("undefined (C ≈ A)" if d is None else
                                   f"{d[0]:.2f} (95% CI {d[1]:.2f} – {d[2]:.2f})"))

    cat = stats.by_category(rows)
    lines += ["", "## By category", "", "| model | arm | " + " | ".join(CATS) + " |",
              "|---|---|" + "---|" * len(CATS)]
    for s in scores:
        lines.append(f"| {s.model} | {s.arm} | " + " | ".join(_pct(cat.get((s.model, s.arm, c), float('nan')))
                                                          for c in CATS) + " |")

    op = stats.operational(rows)
    lines += ["", "## Operational", "",
              "| model | arm | attempts | refused | no submission | tool error rate | protocol errors/attempt | "
              "tool calls | input tok | output tok | latency s |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for (m, a), o in sorted(op.items()):
        lines.append(f"| {m} | {a} | {o['attempts']} | {_pct(o['refused'])} | {_pct(o['no_submission'])} | "
                     f"{_pct(o['tool_error_rate'])} | {o['protocol_errors']:.2f} | {o['tool_calls']:.1f} | "
                     f"{o['input_tokens']:.0f} | {o['output_tokens']:.0f} | {o['latency_s']:.1f} |")

    n_q = len({r['question_id'] for r in rows})
    lines += ["", "## Limits of this result", "",
              f"- n = {n_q} questions. With paired McNemar, differences under ~10–15 pp are unlikely to be "
              "significant at this size; read CIs, not just point estimates.",
              "- TPC-H is public; models may have seen the schema. See the renamed-schema subset when available.",
              "- One semantic layer implementation (MetricFlow) and one glossary; other modeling choices may differ."]
    _chart(scores, out_dir / "ex_by_arm.png")
    lines += ["", "![Execution accuracy by arm](ex_by_arm.png)", ""]
    path = out_dir / "report.md"
    path.write_text("\n".join(lines))
    return path


def aa_test(run_a: str, run_b: str, arm: str) -> stats.PairTest | None:
    """A/A check: the same arm in two runs must not differ significantly."""
    rows = ResultStore().read([run_a, run_b]).to_pylist()
    for r in rows:
        r["arm"] = f"{r['arm']}@{r['run_id']}"
    models = sorted({r["model_id"] for r in rows})
    if len(models) != 1:
        raise SystemExit("A/A test expects both runs to use the same model")
    return stats.paired_test(rows, models[0], f"{arm}@{run_a}", f"{arm}@{run_b}")


def default_out(run_ids: list[str]) -> Path:
    return config.RUNS_DIR / f"report-{'-'.join(run_ids)}"
